#!/usr/bin/env python3
"""Port SirPlease L4D2-Competitive-Rework zonemod stripper cfgs onto a converted campaign.

    ./compstripper.py <name> [<name> ...] [--no-pull]

For every map in out/<name>/pkg/maps that has upstream/L4D2-Competitive-Rework/cfg/stripper/zonemod/maps/<map>.cfg,
stripper2to1.py ports it against out/<name>/src/maps/<map>.bsp (the L4D2 original) and the converted BSP, our
generated header (flow, events, lost Director Scripts) and start-saferoom ammo from rotoblin.py are kept, and
rotated blockers are split by deploy/tools/blocker-angles. The result replaces out/<name>/rotoblin/stripper/<map>.cfg
and the port report goes to out/<name>/rotoblin/compstripper.txt. Maps without an upstream cfg keep rotoblin.py's.
Upstream's nav fixes (scripts/vscripts/nav_fixes/<map>_navfixes.nut, VScript) and the cfg's point_nav_attribute_region
entities go straight into out/<name>/pkg/maps/<map>.nav through navfix.py (idempotent); a standalone run then repacks the
VPK. Maps in onslaught.TABLE then get their L4D2 onslaughts rebuilt (onslaught.py). convert.py runs this after
rotoblin.py; run it alone to refresh a campaign when upstream changes.
"""
import glob, math, os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import navfix, onslaught, rotoblin, stripper2to1

UPSTREAM = os.path.join(HERE, 'upstream', 'L4D2-Competitive-Rework')
UPSTREAM_URL = 'https://github.com/SirPlease/L4D2-Competitive-Rework.git'
MAPS = os.path.join(UPSTREAM, 'cfg', 'stripper', 'zonemod', 'maps')
NAVFIXES = os.path.join(UPSTREAM, 'scripts', 'vscripts', 'nav_fixes')
VENV = os.path.join(HERE, '.venv')
BLOCKER_ANGLES = '/home/volence/l4d/deploy/tools/blocker-angles/blocker_angles.py'
L4D1 = os.path.expanduser('~/.local/share/Steam/steamapps/common/left 4 dead')
# Models a ported cfg may use: stock L4D1, the L4D2 pack every player installs, and the campaign itself.
MODEL_SOURCES = [f'{L4D1}/left4dead/pak01_dir.vpk', f'{L4D1}/left4dead_dlc3/pak01_dir.vpk'] + \
    sorted(glob.glob(f'{L4D1}/left4dead/addons/*l4d2maps_*.vpk'))
# L4D2 particle systems whose renderer L4D1 lacks: the client logs "C_OP_RenderSprites::RenderUnsorted: Attempting to
# use an unimplemented sprite renderer for system ..." every frame (owner's console on Diescraper 1, 2026-10-24).
L4D1_UNDRAWABLE_PARTICLES = {'smoke_exhaust_01'}
START_AMMO_RADIUS = 700  # a ported ammo pile this close to info_player_start makes rotoblin.py's one redundant


def upstream(pull=True):
    if not os.path.isdir(UPSTREAM):
        subprocess.run(['git', 'clone', '-q', '--depth', '1', UPSTREAM_URL, UPSTREAM], check=True)
    elif pull:
        subprocess.run(['git', '-C', UPSTREAM, 'pull', '-q', '--ff-only'], check=True)
    return subprocess.run(['git', '-C', UPSTREAM, 'log', '-1', '--format=%h %cs'],
                          capture_output=True, text=True, check=True).stdout.strip()


def skeleton_parts(text):
    """rotoblin.py's header comments and its start ammo block (None if it added none)."""
    head = []
    for line in text.split('\n'):
        if line.startswith(('; ####', '; =====')):
            break
        if 'then edited by hand' in line:
            continue
        if line.startswith('; from the BSP'):  # second half of rotoblin.py's "Generated by ..., then edited by hand."
            line = '; Positions are' + line[1:]
        head.append(line)
    ammo = re.search(r'^add:\n\{[^{}]*"weapon_ammo_spawn"[^{}]*\}', text, re.M)
    start = re.search(r'start \(info_player_start\)\s+(\S+ \S+ \S+)', text)
    return head, ammo and ammo.group(0), start and [float(x) for x in start.group(1).split()]


def has_ammo_near(cfg, p):
    for b in re.findall(r'^\{[^{}]*\}', cfg, re.M):
        kv = dict(re.findall(r'"([^"]+)"\s+"([^"]*)"', b))
        if kv.get('classname') == 'weapon_ammo_spawn' and 'origin' in kv:
            if math.dist(p, [float(x) for x in kv['origin'].split()[:3]]) < START_AMMO_RADIUS:
                return True
    return False


def port_campaign(name, rev, models_ok, repack=False):
    work = os.path.join(HERE, 'out', name)
    outdir = os.path.join(work, 'rotoblin', 'stripper')
    gendir = os.path.join(work, 'rotoblin', 'generated')  # rotoblin.py's cfgs, kept for their headers
    os.makedirs(gendir, exist_ok=True)
    pkg = os.path.join(work, 'pkg')
    maps = [os.path.basename(b)[:-4] for b in sorted(glob.glob(os.path.join(pkg, 'maps', '*.bsp')))]
    def ported(m):
        p = os.path.join(outdir, m + '.cfg')
        return os.path.exists(p) and open(p, encoding='latin1').read().startswith('; Ported from')
    if any(ported(m) and not os.path.exists(os.path.join(gendir, m + '.cfg')) for m in maps):
        rotoblin.main(pkg)  # a campaign ported before generated/ existed: regenerate (deterministic)
    for m in maps:
        p = os.path.join(outdir, m + '.cfg')
        if os.path.exists(p) and not ported(m):
            shutil.copyfile(p, os.path.join(gendir, m + '.cfg'))
    ported, report, nav_changed = [], [], []
    for bsp in sorted(glob.glob(os.path.join(work, 'pkg', 'maps', '*.bsp'))):
        m = os.path.basename(bsp)[:-4]
        cfg = os.path.join(MAPS, m + '.cfg')
        src = os.path.join(work, 'src', 'maps', m + '.bsp')
        if not os.path.exists(cfg):
            continue
        if not os.path.exists(src):
            report.append(f'!! {m}: upstream has a cfg but out/{name}/src/maps/{m}.bsp is missing (rerun convert.py)')
            continue
        body, rep, stats = stripper2to1.port(open(cfg, encoding='latin1').read(), stripper2to1.load_ents(src),
                                              stripper2to1.load_ents(bsp), models_ok)
        mine, gen = os.path.join(outdir, m + '.cfg'), os.path.join(gendir, m + '.cfg')
        head, ammo, start = skeleton_parts(open(gen, encoding='latin1').read()) if os.path.exists(gen) else ([], None, None)
        intro = [f'; Ported from SirPlease/L4D2-Competitive-Rework {rev} cfg/stripper/zonemod/maps/{m}.cfg',
                 '; by l4d2to1/compstripper.py, matches checked against the converted BSP. Lines tagged [L4D1] say',
                 '; what changed; blocks commented out under them have no L4D1 equivalent.', ';']
        tail = ''
        if ammo and start and not has_ammo_near(body, start):
            tail = '\n\n; --- [L4D1] start saferoom ammo pile (the conversion has none near info_player_start)\n' + ammo + '\n'
        open(mine, 'w', encoding='latin1').write('\n'.join(intro + head) + '\n' + body.rstrip('\n') + tail + '\n')
        dead_fx = sorted({kv.get('effect_name') for kv in stripper2to1.load_ents(bsp) if kv.get('classname') == 'info_particle_system'
                          and kv.get('effect_name') in L4D1_UNDRAWABLE_PARTICLES})
        if dead_fx:  # the L4D1 client cannot draw these: console spam every frame, nothing on screen
            with open(mine, 'a', encoding='latin1') as fh:
                fh.write('\n; --- [L4D1] particle systems the L4D1 client cannot render ("Attempting to use an unimplemented'
                         ' sprite renderer"), every frame\nfilter:\n' + ''.join(
                             f'{{\n\t"classname" "info_particle_system"\n\t"effect_name" "{fx}"\n}}\n' for fx in dead_fx))
            report.append(f'{m}: filtered undrawable particles {", ".join(dead_fx)}')
        if m in onslaught.TABLE:  # the L4D2 onslaughts VScript ran, rebuilt with director_panic_forever
            onslaught.apply(mine, m)
            report.append(f'{m}: onslaught rebuilt ({onslaught.TABLE[m][3]})')
        ported.append(mine)
        report.append(f'{m}: {dict(stats)}')
        report += ['   ' + r for r in rep]
        # Comp Rework's nav fixes are VScript (+ point_nav_attribute_region in the cfg): write them into the nav
        nut = os.path.join(NAVFIXES, m + '_navfixes.nut')
        ops = navfix.nut_ops(open(nut).read()) if os.path.exists(nut) else []
        regions = navfix.cfg_regions(open(cfg, encoding='latin1').read())
        navp = os.path.join(work, 'pkg', 'maps', m + '.nav')
        if (ops or regions) and os.path.exists(navp):
            old = open(navp, 'rb').read()
            new, log = navfix.apply(old, ops, regions)
            if new != old:
                open(navp, 'wb').write(new)
                nav_changed.append(m)
            report += ['   nav: ' + l for l in log]
    if ported:
        r = subprocess.run([sys.executable, BLOCKER_ANGLES, '--cap', '96', '--write'] + ported,
                           capture_output=True, text=True, check=True)
        report += ['blocker-angles: ' + l for l in r.stdout.splitlines() if 'OVER TOL' in l or 'LEFT AS IS' in l
                   or 'rotated blockers' in l]
    if nav_changed and repack:
        vpk = os.path.join(work, f'{name}_l4d1.vpk')
        subprocess.run([VENV + '/bin/python', '-c', 'import sys, vpk; p = vpk.new(sys.argv[1]); p.version = 1; p.save(sys.argv[2])',
                        os.path.join(work, 'pkg'), vpk], check=True, cwd='/tmp')
        report.append(f'nav fixes changed {", ".join(nav_changed)}: repacked {os.path.basename(vpk)}')
    open(os.path.join(work, 'rotoblin', 'compstripper.txt'), 'w').write(
        f'Comp Rework {rev}: {len(ported)} maps ported\n' + '\n'.join(report) + '\n')
    return ported, report


def model_checker(name):
    have = stripper2to1.model_index(MODEL_SOURCES + [os.path.join(HERE, 'out', name, 'pkg')])
    return lambda m: m.lower() in have


def main(names, pull=True, repack=False):
    """repack: rebuild the VPK when a nav fix changed a nav (standalone runs; under convert.py, dictbuild.sh repacks)."""
    rev = upstream(pull)
    out = []
    for name in names:
        ported, _ = port_campaign(name, rev, model_checker(name), repack)
        out.append(f'{name}: {len(ported)} maps ported from Comp Rework {rev}')
    return out


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if not args:
        sys.exit(__doc__)
    print('\n'.join(main(args, pull='--no-pull' not in sys.argv, repack=True)))
